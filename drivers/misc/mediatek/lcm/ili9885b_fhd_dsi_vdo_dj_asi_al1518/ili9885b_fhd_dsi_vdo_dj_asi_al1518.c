static void init(void)
{
 int rc;
 initialized = false;
 if (!util.mdelay || !util.udelay || !util.dsi_set_cmdq_V2) {
  pr_err("u20 panel: incomplete DSI utilities\n"); return;
 }
 if (bias(true)) return;
 rc = u20_lcd_bias_write(0, 0x0d);
 if (!rc) rc = u20_lcd_bias_write(1, 0x0d);
 if (rc) { pr_err("u20 panel: bias write failed: %d\n", rc); bias(false); return; }
 (util.mdelay)(2);
 if (reset(1)) goto power_off;
 (util.mdelay)(1);
 if (reset(0)) goto power_off;
 (util.mdelay)(10);
 if (reset(1)) goto power_off;
 (util.mdelay)(120);
 push(init_commands, ARRAY_SIZE(init_commands));
 initialized = true;
 return;
power_off:
 bias(false);
}
static void suspend(void)
{
 if (initialized) {
  push(suspend_commands, ARRAY_SIZE(suspend_commands));
  (util.mdelay)(10);
 }
 initialized = false;
 if (util.mdelay) bias(false);
}
static void resume(void) { init(); }
static unsigned int compare_id(void)
{
 unsigned int request = 0x00023700;
 unsigned char data[2] = { 0 };
 if (!util.mdelay || !util.dsi_set_cmdq || !util.dsi_dcs_read_lcm_reg_v2) return 0;
 if (reset(1) || reset(0)) return 0;
 (util.mdelay)(1);
 if (reset(1)) return 0;
 (util.mdelay)(50);
 util.dsi_set_cmdq(&request, 1, 1);
 if (util.dsi_dcs_read_lcm_reg_v2(0xbf, data, 2) != 2) return 0;
 return data[0] == 0x98;
}
static void backlight(void *handle, unsigned int level)
{
 unsigned char value = level;
 (void)handle;
 if (initialized) util.dsi_set_cmdq_V2(0x51, 1, &value, 1);
}
