static int state(DTS_GPIO_STATE value)
{
 long rc = disp_dts_gpio_select_state(value);
 if (rc) pr_err("u20 panel: state %u failed: %ld\n", value, rc);
 return rc;
}
static int reset(unsigned int value)
{
 return state(value ? DTS_GPIO_STATE_LCM_RST_OUT1 : DTS_GPIO_STATE_LCM_RST_OUT0);
}
static int bias(bool enabled)
{
 int rc;
 if (enabled) {
  rc = state(DTS_GPIO_STATE_U20_LCD_BIAS_ENN1);
  if (rc) return rc;
  rc = state(DTS_GPIO_STATE_U20_LCD_BIAS_ENP1);
  if (rc) state(DTS_GPIO_STATE_U20_LCD_BIAS_ENN0);
  return rc;
 }
 rc = state(DTS_GPIO_STATE_U20_LCD_BIAS_ENP0);
 (util.mdelay)(1);
 return rc ? rc : state(DTS_GPIO_STATE_U20_LCD_BIAS_ENN0);
}
static void push(const struct panel_command *commands, unsigned int count)
{
 unsigned int i;
 for (i = 0; i < count; ++i) {
  const struct panel_command *c = &commands[i];
  switch (c->command) {
  case 0xfffc: (util.mdelay)(c->count); break;
  case 0xfffb: (util.udelay)(c->count); break;
  case 0xfffd: break;
  default: util.dsi_set_cmdq_V2(c->command, c->count, (unsigned char *)c->data, 1); break;
  }
 }
}
